  function roundPath(pts) {
    let d = `M${pts[0][0].toFixed(1)} ${pts[0][1].toFixed(1)}`;
    for (let i = 1; i < pts.length - 1; i++) {
      const [x0, y0] = pts[i - 1], [x1, y1] = pts[i], [x2, y2] = pts[i + 1];
      const r = Math.min(12, Math.hypot(x1 - x0, y1 - y0) / 2, Math.hypot(x2 - x1, y2 - y1) / 2);
      const ax = x1 - Math.sign(x1 - x0) * r, ay = y1 - Math.sign(y1 - y0) * r, bx = x1 + Math.sign(x2 - x1) * r, by = y1 + Math.sign(y2 - y1) * r;
      d += `L${ax.toFixed(1)} ${ay.toFixed(1)}Q${x1.toFixed(1)} ${y1.toFixed(1)} ${bx.toFixed(1)} ${by.toFixed(1)}`;
    }
    const e = pts[pts.length - 1]; return d + `L${e[0].toFixed(1)} ${e[1].toFixed(1)}`;
  }
  function route(a, b, salt = "") {
    const A = cur.get(a), B = cur.get(b); if (!A || !B) return null;
    const ra = RC(A), rb = RC(B), off = ((hash(a + b + salt) % 9) - 4) * 5;
    const pa = (r, side) => { const span = side === "l" || side === "r" ? r.b - r.t : r.r - r.l; const k = ((hash(b + a + salt) % 5) - 2) * Math.min(10, span / 8);
      return side === "r" ? [r.r, r.cy + k] : side === "l" ? [r.l, r.cy + k] : side === "b" ? [r.cx + k, r.b] : [r.cx + k, r.t]; };
    const la = A.lane, lb = B.lane;
    let pts;
    if (la >= 0 && lb >= 0 && la !== lb) {
      const LA = laneRect(la), LB = laneRect(lb), toRight = LB.x > LA.x;
      const sa = toRight ? "r" : "l", sb = toRight ? "l" : "r";
      const p0 = pa(ra, sa), p3 = pa(rb, sb);
      const adj = Math.abs(la - lb) === 1;
      if (adj) { const mx = corridorBetween(LA, LB) + off; pts = [p0, [mx, p0[1]], [mx, p3[1]], p3]; }
      else {
        const exitX = (toRight ? LA.x + LA.w + 12 : LA.x - 12) + off * .6, entryX = (toRight ? LB.x - 12 : LB.x + LB.w + 12) + off * .6;
        const laneBottom = Math.max(...lanesT.map((l) => l.y + l.h)), useTop = (p0[1] + p3[1]) / 2 < laneBottom * .55;
        const busY = useTop ? -16 - (hash(a + b) % 8) * 8 : laneBottom + 16 + (hash(a + b) % 8) * 8;
        pts = [p0, [exitX, p0[1]], [exitX, busY], [entryX, busY], [entryX, p3[1]], p3];
        pts.labelSeg = 4;
      }
    } else if (la >= 0 && la === lb && A.d === 1 && B.d === 1 || (la === lb && !sameBox(a, b) && la >= 0)) {
      const Ln = laneRect(la), side = state.lang === "ar" ? "l" : "r";
      const cx = (side === "r" ? Ln.x + Ln.w - 10 : Ln.x + 10) + off * .5;
      const p0 = pa(ra, side), p3 = pa(rb, side);
      pts = [p0, [cx, p0[1]], [cx, p3[1]], p3];
    } else {
      if (rb.l >= ra.r + 6 || rb.r <= ra.l - 6) {
        const right = rb.l >= ra.r; const p0 = pa(ra, right ? "r" : "l"), p3 = pa(rb, right ? "l" : "r");
        const mx = (right ? (ra.r + rb.l) / 2 : (ra.l + rb.r) / 2) + off * .3; pts = [p0, [mx, p0[1]], [mx, p3[1]], p3];
      } else {
        const down = rb.t >= ra.b; const p0 = pa(ra, down ? "b" : "t"), p3 = pa(rb, down ? "t" : "b");
        const my = (down ? (ra.b + rb.t) / 2 : (ra.t + rb.b) / 2); pts = [p0, [p0[0], my], [p3[0], my], p3];
      }
    }
    const labelSeg = pts.labelSeg;
    pts = pts.filter((p, i) => i === 0 || Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) > .5);
    let best = 0, bl = -1;
    for (let i = 1; i < pts.length; i++) { const l = Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]); if (l > bl) { bl = l; best = i; } }
    if (labelSeg && pts.length === 6 && Math.abs(pts[4][1] - pts[3][1]) > 50) best = 4;
    const mid = [(pts[best][0] + pts[best - 1][0]) / 2, (pts[best][1] + pts[best - 1][1]) / 2];
    const e = pts[pts.length - 1], p = pts[pts.length - 2]; const ang = Math.atan2(e[1] - p[1], e[0] - p[0]);
    let len = 0; for (let i = 1; i < pts.length; i++) len += Math.hypot(pts[i][0] - pts[i - 1][0], pts[i][1] - pts[i - 1][1]);
    return { d: roundPath(pts), mid, end: e, ang, len };
  }
